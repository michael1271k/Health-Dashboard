#!/usr/bin/env node
/**
 * Generate `DomsMap.swift` from the TypeScript soreness vocabularies.
 *
 * ── WHY THIS EXISTS ──────────────────────────────────────────────────────────
 * `DomsMap.swift` was a hand-typed `[String]` with no generator and no parity
 * test, and `AtlasHitTests` only ever asserted that its landmarks were a SUBSET
 * of the sixteen. So a DOMS muscle could be added on the web, be invisible on
 * iOS, and leave `npm run check` and `swift test` both green — which is exactly
 * how `Inner thighs` shipped in September 2026 with the tracker's own docstring
 * still saying nine.
 *
 * v2 adds three more vocabularies both platforms have to agree on (sub-regions,
 * sides, joints), so the hand-copy stops here.
 *
 * ── WHAT IT READS ────────────────────────────────────────────────────────────
 *   · DOMS_MUSCLES, DOMS_LEVELS           src/lib/hooks/useRecovery.ts
 *   · DOMS_TO_LANDMARK                    src/lib/body/atlas.ts
 *   · SUB_REGIONS, JOINTS, SORENESS_SIDES src/lib/body/subRegions.ts
 *
 * Parsed with regexes rather than imported, for the reason `gen-atlas-swift.mjs`
 * gives: node cannot import a `.ts`, and a build step to read one literal array
 * is a build step to maintain forever.
 *
 * This script touches NO database. It reads three files and writes one.
 *
 * Usage: npm run doms   ·   npm run check:doms
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const SOURCES = {
  recovery: join(ROOT, 'src/lib/hooks/useRecovery.ts'),
  atlas: join(ROOT, 'src/lib/body/atlas.ts'),
  sub: join(ROOT, 'src/lib/body/subRegions.ts'),
}
export const TARGET = join(ROOT, 'native/Onyx/Features/Pulse/DomsMap.swift')

/** Pull `export const NAME = [ 'a', 'b' ] as const` into a JS array. */
function stringArray(src, name) {
  const m = src.match(new RegExp(`export const ${name} = \\[([\\s\\S]*?)\\] as const`))
  if (!m) throw new Error(`${name}: not found`)
  return [...m[1].matchAll(/'([^']+)'/g)].map((x) => x[1])
}

/** Pull `{ v: 0, label: 'None' }, …` out of DOMS_LEVELS, in order. */
function levels(src) {
  const m = src.match(/export const DOMS_LEVELS = \[([\s\S]*?)\] as const/)
  if (!m) throw new Error('DOMS_LEVELS: not found')
  return [...m[1].matchAll(/label:\s*'([^']+)'/g)].map((x) => x[1])
}

/**
 * Pull an object literal of string lists into [key, values][].
 *
 * Comments inside the literal are stripped first: both sources carry prose
 * between entries, and an apostrophe in a comment would otherwise be read as a
 * string delimiter.
 */
function recordOfLists(src, name) {
  const m = src.match(new RegExp(`export const ${name}[^=]*= \\{([\\s\\S]*?)\\n\\}`))
  if (!m) throw new Error(`${name}: not found`)
  const body = m[1].replace(/\/\/[^\n]*/g, '').replace(/\/\*[\s\S]*?\*\//g, '')
  return [...body.matchAll(/(?:'([^']+)'|([A-Za-z][\w/]*))\s*:\s*\[([^\]]*)\]/g)]
    .map((x) => [x[1] ?? x[2], [...x[3].matchAll(/'([^']+)'/g)].map((y) => y[1])])
}

/** 'Abs/core' → absCore, 'Upper back' → upperBack. The Swift enum's case names. */
function swiftCase(display) {
  const parts = display.split(/[^A-Za-z0-9]+/).filter(Boolean)
  return parts[0].toLowerCase() + parts.slice(1).map((p) => p[0].toUpperCase() + p.slice(1)).join('')
}

const q = (s) => `"${s}"`
const list = (xs) => `[${xs.map(q).join(', ')}]`

export function generate({ recovery, atlas, sub }) {
  const muscles = stringArray(recovery, 'DOMS_MUSCLES')
  const words = levels(recovery)
  const toLandmark = recordOfLists(atlas, 'DOMS_TO_LANDMARK')
  const subRegions = recordOfLists(sub, 'SUB_REGIONS')
  const joints = stringArray(sub, 'JOINTS')
  const sides = stringArray(sub, 'SORENESS_SIDES')

  const landmarkRows = muscles.map((m) => {
    const hit = toLandmark.find(([k]) => k === m)
    if (!hit) throw new Error(`DOMS_TO_LANDMARK has no entry for ${m}`)
    return `        ${q(m)}: [${hit[1].map((l) => `.${swiftCase(l)}`).join(', ')}],`
  }).join('\n')

  const subRows = muscles
    .filter((m) => subRegions.some(([k]) => k === m))
    .map((m) => `        ${q(m)}: ${list(subRegions.find(([k]) => k === m)[1])},`)
    .join('\n')

  return `// GENERATED by scripts/gen-doms-swift.mjs — DO NOT EDIT BY HAND.
//
// Source of truth:
//   · DOMS_MUSCLES, DOMS_LEVELS           src/lib/hooks/useRecovery.ts
//   · DOMS_TO_LANDMARK                    src/lib/body/atlas.ts
//   · SUB_REGIONS, JOINTS, SORENESS_SIDES src/lib/body/subRegions.ts
//
// Re-run \`npm run doms\` after changing any of those. \`npm run check:doms\`
// fails if this file is stale, and it is part of \`npm run check\`.

import OnyxCore

/// The soreness vocabularies, mirrored from the web.
///
/// The GROUP is what a user rates (a sore arm is a sore arm); the landmarks are
/// what the figure draws; the sub-region is optional detail the scoring engine
/// never reads. Severity 0…3 becomes intensity 0…1 because the atlas draws
/// AMOUNT and passes no verdicts.
enum DomsMap {

    /// Display order: upper, trunk, lower — as the web lists them.
    static let muscles = ${list(muscles)}

    /// Index IS the stored severity.
    static let levels = ${list(words)}

    static let maxSeverity = ${words.length - 1}

    /// Stored \`side\` values. \`both\` is the default and the pre-v2 meaning.
    static let sides = ${list(sides)}

    /// Non-muscle complaint points. Never scored, never a landmark.
    static let joints = ${list(joints)}

    /// Sub-regions of the muscles that have them. A muscle absent here is
    /// always rated whole; a muscle present here may still be rated whole.
    static let subRegions: [String: [String]] = [
${subRows}
    ]

    static let landmarks: [String: [LandmarkMuscle]] = [
${landmarkRows}
    ]

    /// The muscle a sub-region belongs to — the fold that keeps the ten intact.
    static let parentOfSubRegion: [String: String] = subRegions.reduce(into: [:]) { out, pair in
        for sub in pair.value { out[sub] = pair.key }
    }

    /// \`domsToWorked\` — group → severity becomes landmark → 0…1, max-merged.
    static func worked(_ severity: [String: Int]) -> [LandmarkMuscle: Double] {
        var out: [LandmarkMuscle: Double] = [:]
        for (muscle, s) in severity where s > 0 {
            let intensity = min(1, max(0, Double(s) / Double(maxSeverity)))
            for landmark in landmarks[muscle] ?? [] {
                out[landmark] = max(out[landmark] ?? 0, intensity)
            }
        }
        return out
    }

    /// "Quads moderate · Chest mild", in display order; nil when nothing is sore.
    static func summary(_ severity: [String: Int]) -> String? {
        let sore = muscles.compactMap { m -> String? in
            guard let s = severity[m], s > 0, s < levels.count else { return nil }
            return "\\(m) \\(levels[s].lowercased())"
        }
        return sore.isEmpty ? nil : sore.joined(separator: " · ")
    }
}

extension DomsMap {
    /// The group a landmark belongs to — the reverse of \`landmarks\`, which is
    /// what a tap on the body needs: the atlas answers in landmarks (sixteen)
    /// and soreness is rated in groups (ten).
    static let groupOfLandmark: [LandmarkMuscle: String] = landmarks.reduce(into: [:]) { out, pair in
        for landmark in pair.value { out[landmark] = pair.key }
    }

    static func group(of landmark: LandmarkMuscle) -> String? { groupOfLandmark[landmark] }
}
`
}

// ── CLI ──
if (process.argv[1] && process.argv[1].endsWith('gen-doms-swift.mjs')) {
  const out = generate({
    recovery: readFileSync(SOURCES.recovery, 'utf8'),
    atlas: readFileSync(SOURCES.atlas, 'utf8'),
    sub: readFileSync(SOURCES.sub, 'utf8'),
  })
  if (process.argv.includes('--check')) {
    if (readFileSync(TARGET, 'utf8') !== out) {
      console.error(`${TARGET} is stale — re-run \`npm run doms\``)
      process.exit(1)
    }
    console.log('✔ DomsMap.swift matches the TypeScript vocabularies')
  } else {
    writeFileSync(TARGET, out)
    console.log(`✔ wrote ${TARGET}`)
  }
}
